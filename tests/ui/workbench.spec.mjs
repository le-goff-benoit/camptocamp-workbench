test('each project restores its terminals and asks Codex, Claude or a shell', async ({ page }) => {
  const fixture=JSON.parse(readFileSync('.runtime/qa.json','utf8'));
  await page.goto('/workbench/#access='+fixture.token);
  await page.getByRole('button',{name:'Projet atlas-demo',exact:true}).click();
  await expect(page.getByRole('heading',{name:'atlas-demo',exact:true})).toBeVisible();
  const initial=await page.locator('#terminal-tabs [role=tab]').count();
  await page.getByRole('button',{name:'Terminal du projet',exact:true}).click();
  const chooser=page.getByRole('menu',{name:'Ouvrir un terminal'});
  await expect(chooser.getByRole('menuitem',{name:'Ouvrir Codex'})).toBeFocused();
  await expect(chooser.getByRole('menuitem',{name:'Ouvrir Claude'})).toBeVisible();
  await chooser.getByRole('menuitem',{name:'Shell simple'}).click();
  const view=()=>page.locator('.terminal-view:not([hidden])');
  await expect(view().locator('.xterm-screen')).toContainText('bash-5.1$');
  const atlasTerminal=await view().getAttribute('data-id');
  await view().locator('textarea').pressSequentially('pwd');await view().locator('textarea').press('Enter');
  await expect(view().locator('.xterm-screen')).toContainText(fixture.repo);
  await page.getByRole('button',{name:'Projet boreal-demo',exact:true}).click();
  await expect(page.locator('#terminal-panel')).toBeHidden();
  await page.getByRole('button',{name:'Terminal du projet',exact:true}).click();
  await page.getByRole('menuitem',{name:'Shell simple'}).click();
  await expect(page.locator('#terminal-tabs [role=tab]')).toHaveCount(1);
  await expect(page.locator('#terminal-scope')).toHaveText('boreal-demo');
  await expect(view().locator('.xterm-screen')).toContainText('bash-5.1$');
  await view().locator('textarea').pressSequentially('pwd');await view().locator('textarea').press('Enter');
  await expect(view().locator('.xterm-screen')).toContainText(fixture.other_repo);
  await page.getByRole('button',{name:'Projet atlas-demo',exact:true}).click();
  await expect(page.locator('#terminal-tabs [role=tab]')).toHaveCount(initial+1);
  await expect(view()).toHaveAttribute('data-id',atlasTerminal);
  await expect(view().locator('.xterm-screen')).toContainText(fixture.repo);
  await page.getByRole('button',{name:'Nouveau terminal',exact:true}).click();
  await page.getByRole('menuitem',{name:'Ouvrir Codex'}).click();
  await expect(view().locator('.xterm-screen')).toContainText('Codex prêt · atlas-demo');
  await expect(page.locator('#terminal-tabs [role=tab][aria-selected=true] .logo')).toHaveCount(1);
  await page.getByRole('button',{name:'Nouveau terminal',exact:true}).click();
  await page.keyboard.press('ArrowRight');await page.keyboard.press('Enter');
  await expect(view().locator('.xterm-screen')).toContainText('Claude prêt · atlas-demo');
  await page.screenshot({path:'.runtime/terminal-0.4.png'});
  await page.getByRole('button',{name:'Réduire le terminal',exact:true}).click();
  await expect(page.locator('#terminal-panel')).toHaveClass(/minimized/);
  await expect(page.locator('#terminal-tabs [role=tab]')).toHaveCount(initial+3);
  await page.getByRole('tab',{name:'Mesures',exact:true}).click();
  await expect(page.locator('#terminal-panel')).toHaveClass(/minimized/);
  await page.screenshot({path:'.runtime/terminal-min-0.4.png'});
  await page.getByRole('button',{name:'Terminal du projet',exact:true}).click();
  await expect(page.locator('#terminal-panel')).not.toHaveClass(/minimized/);
  await expect(view().locator('.xterm-screen')).toContainText('Claude prêt · atlas-demo');
});

